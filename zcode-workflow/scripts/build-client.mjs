/**
 * Build `client.js` from `client-src/*.js`.
 *
 * The served browser artifact is one plain-JavaScript factory body: parts are concatenated in
 * file-name order, and the locale dictionaries are embedded from `locale/*.json` so the JSON files
 * stay the single source of copy. Run `node scripts/build-client.mjs` after editing any part.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = (name) => readFileSync(path.join(root, name), 'utf8');
const json = (name) => JSON.parse(read(name));
const en = json('locale/en.json');
const zh = json('locale/zh.json');
const toolEn = en.tool ?? {};
const toolZh = zh.tool ?? {};
const uiEn = { ...(en.ui ?? {}) };
const uiZh = { ...(zh.ui ?? {}) };
// Surface-specific copy lives in one fragment per part so contributors never edit the same JSON.
const uiDir = path.join(root, 'locale', 'ui');
if (existsSync(uiDir)) {
  for (const name of readdirSync(uiDir).filter((entry) => entry.endsWith('.json')).sort()) {
    const fragment = JSON.parse(readFileSync(path.join(uiDir, name), 'utf8'));
    Object.assign(uiEn, fragment.en ?? {});
    Object.assign(uiZh, fragment.zh ?? {});
  }
}
const settingsEn = en.settings ?? {};
const settingsZh = zh.settings ?? {};

const dict = (value) => JSON.stringify(value, null, 2).replace(/\n/g, '\n    ');
const parts = readdirSync(path.join(root, 'client-src'))
  .filter((name) => /^\d+.*\.js$/u.test(name))
  .sort();
const body = parts.map((name) => `/* ---- client-src/${name} ---- */\n${read('client-src/' + name)}`).join('\n');

const output = `/**
 * zcode-workflow browser half (generated by scripts/build-client.mjs — edit client-src/*.js and rebuild).
 *
 * Registers the workflow tool cards, the workflow directory main panel, the run-detail right
 * Sidebar tab, the session status entry and the settings row. Data comes from the package's own
 * same-origin routes under /zcode-workflow; no Host RPC is used.
 */
window.__ModuleLoader__.load({
  id: 'zcode-workflow',
  factory(require) {
    const React = require('react');

    /** English dictionary; also the per-string fallback when a namespace lookup misses. */
    const EN = ${dict(toolEn)};
    /** Chinese dictionary; every key of EN must be present. */
    const ZH = ${dict(toolZh)};
    const UI_EN = ${dict(uiEn)};
    const UI_ZH = ${dict(uiZh)};
    const SETTINGS_EN = ${dict(settingsEn)};
    const SETTINGS_ZH = ${dict(settingsZh)};

${body}
  },
});
`;

writeFileSync(path.join(root, 'client.js'), output);
console.log(`built client.js from ${parts.length} parts (${output.length} bytes)`);
